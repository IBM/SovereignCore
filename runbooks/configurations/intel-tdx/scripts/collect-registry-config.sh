#!/usr/bin/env bash
# Generate image-rs registry mappings from hub and optional tenant mirror resources.
# Prerequisites: oc, jq, python3; site config, authenticated kubeconfigs and trusted mirror CA.
# Effects: Writes registry-configuration.toml and optionally mirror-ca.pem in COCO_SECRETS_DIR.
# Exit: 0 success/help; nonzero on invalid options, missing trust or collection failure.
# Load registry-config into KBS before guests reference it, or all guest pulls fail.
# Trust CA files or authenticated API data only; never learn trust from an unverified TLS peer.
# ENV (name: meaning; default in parentheses)
#  INSECURE_MIRRORS  "true" forces `insecure = true` (HTTP). Default "false".
#  EXTRACT_CA  "true" (default) write the mirror CA bundle.
#  MIRROR_CA_FILE  trusted CA bundle (site value; otherwise hub additionalTrustedCA)
#  SITE / SITE_ENV  site config (required; supplies EXPECT_HUB_API_SERVER).
#  KUBECTL  hub client, may be multi-word (oc --kubeconfig=<site HUB_KUBECONFIG>).
#  EXTRA_KUBECONFIGS  colon-separated tenant kubeconfigs merged into the shared guest mappings (unset)
#  COCO_SECRETS_DIR  Local material dir (default: ~/.coco-pattern).
# Options: -o/--output PATH; --insecure (HTTP); --secure (HTTPS); --no-ca; --no-auth (no-op); -h/--help.

set -euo pipefail

. "$(dirname "${BASH_SOURCE[0]}")/lib/site.sh"
KUBECTL="${KUBECTL:-oc --kubeconfig=${HUB_KUBECONFIG}}"
COCO_SECRETS_DIR="${COCO_SECRETS_DIR:-${HOME}/.coco-pattern}"
OUTPUT_FILE="${COCO_SECRETS_DIR}/registry-configuration.toml"
CA_FILE="${COCO_SECRETS_DIR}/mirror-ca.pem"
INSECURE_MIRRORS="${INSECURE_MIRRORS:-false}"
EXTRACT_CA="${EXTRACT_CA:-true}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    -o|--output) OUTPUT_FILE="$2"; shift 2 ;;
    --insecure)  INSECURE_MIRRORS="true"; shift ;;
    --secure)    INSECURE_MIRRORS="false"; shift ;;
    --no-ca)     EXTRACT_CA="false"; shift ;;
    --no-auth)   shift ;;
    -h|--help)   sed -n '2,/^[^#]/{/^#/s/^# \{0,1\}//p}' "$0"; exit 0 ;;
    *) echo "Error: unknown option $1" >&2; exit 1 ;;
  esac
done

msg()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mWARN:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

command -v "${KUBECTL%% *}" >/dev/null 2>&1 || die "'${KUBECTL%% *}' not found in PATH"
command -v jq           >/dev/null 2>&1 || die "'jq' not found in PATH"
command -v python3      >/dev/null 2>&1 || die "'python3' not found in PATH"
. "$(dirname "${BASH_SOURCE[0]}")/lib/cluster-guard.sh"
cluster_guard hub "${KUBECTL}"
${KUBECTL} whoami >/dev/null 2>&1 || die "'${KUBECTL}' is not logged in to the cluster"

mkdir -p "$(dirname "${OUTPUT_FILE}")"

msg "Collecting mirror mappings from ImageDigestMirrorSet / ImageTagMirrorSet / ImageContentSourcePolicy"

mappings() {
  local k=(); [ -z "${1:-}" ] || k=(--kubeconfig="$1")
  ${KUBECTL} "${k[@]}" get imagedigestmirrorset -o json 2>/dev/null \
    | jq -c '[.items[].spec.imageDigestMirrors[]?   | {source, mirrors}]'
  ${KUBECTL} "${k[@]}" get imagetagmirrorset -o json 2>/dev/null \
    | jq -c '[.items[].spec.imageTagMirrors[]?      | {source, mirrors}]'
  ${KUBECTL} "${k[@]}" get imagecontentsourcepolicy -o json 2>/dev/null \
    | jq -c '[.items[].spec.repositoryDigestMirrors[]? | {source, mirrors}]'
}
MAPPINGS_JSON="$(
  {
    mappings
    IFS=: read -ra EXTRA <<<"${EXTRA_KUBECONFIGS:-}"
    for kc in "${EXTRA[@]}"; do
      [ -n "${kc}" ] || continue
      ${KUBECTL} --kubeconfig="${kc}" whoami >/dev/null 2>&1 || die "EXTRA_KUBECONFIGS: cannot reach ${kc}"
      msg "  + mirror mappings from ${kc}" >&2
      mappings "${kc}"
    done
  } | jq -s 'add // []'
)"

COUNT="$(printf '%s' "${MAPPINGS_JSON}" | jq 'length')"
[ "${COUNT}" -gt 0 ] 2>/dev/null || die "no mirror mappings found (IDMS/ITMS/ICSP all empty). Is this a disconnected cluster?"

# image-rs accepts only prefix/location and mirror location/insecure; omit host-only registry fields.
# Pass mappings in a file because stdin carries the Python program.
MAPPINGS_FILE="$(mktemp)"
trap 'rm -f "${MAPPINGS_FILE}"' EXIT
printf '%s' "${MAPPINGS_JSON}" > "${MAPPINGS_FILE}"
INSECURE_MIRRORS="${INSECURE_MIRRORS}" python3 - "${OUTPUT_FILE}" "${MAPPINGS_FILE}" <<'PY'
import json, os, sys
from collections import OrderedDict

out_path = sys.argv[1]
insecure = os.environ.get("INSECURE_MIRRORS", "true").strip().lower() in ("1", "true", "yes")
with open(sys.argv[2]) as fh:
    items = json.load(fh)

reg = OrderedDict()
for it in items:
    src = (it or {}).get("source")
    if not src:
        continue
    reg.setdefault(src, [])
    for m in (it.get("mirrors") or []):
        if m and m not in reg[src]:
            reg[src].append(m)

lines = [
    "# image-rs registry configuration for the CoCo guest (guest-pull image mirroring).",
    "# GENERATED by scripts/collect-registry-config.sh from the cluster's",
    "# ImageDigestMirrorSet + ImageTagMirrorSet (+ ImageContentSourcePolicy).",
    "# Do not edit by hand; re-run the script to regenerate.",
    "#",
    "# Loaded into Vault (secret/hub/registryConfig) by load-existing-vault.sh and",
    "# served to the guest as the KBS resource kbs:///default/registry-config/config.",
    "",
]
for src, mirrors in reg.items():
    if not mirrors:
        continue
    lines.append("[[registry]]")
    lines.append('prefix = "%s"' % src)
    lines.append('location = "%s"' % src)
    for m in mirrors:
        lines.append("")
        lines.append("[[registry.mirror]]")
        lines.append('location = "%s"' % m)
        if insecure:
            lines.append("insecure = true")
    lines.append("")

with open(out_path, "w") as f:
    f.write("\n".join(lines).rstrip("\n") + "\n")

print("registries=%d insecure_mirrors=%s" % (len([s for s, m in reg.items() if m]), insecure))
PY

msg "Wrote ${OUTPUT_FILE}"
msg "  $(grep -c '^\[\[registry\]\]' "${OUTPUT_FILE}") registry entries, insecure_mirrors=${INSECURE_MIRRORS}"

MIRROR_HOSTS="$(grep -E '^location = ' "${OUTPUT_FILE}" \
  | sed -E 's/^location = "([^"]+)".*/\1/' \
  | grep -E '[.:/]' | grep -vE '^(quay\.io|registry\.(access\.)?redhat\.(com|io)|docker\.io|registry\.connect\.redhat\.com|gcr\.io|ghcr\.io)' \
  | sed -E 's#/.*$##' | sort -u)"

if [ "${EXTRACT_CA}" = "true" ] && [ "${INSECURE_MIRRORS}" != "true" ]; then
  if [ -n "${MIRROR_CA_FILE:-}" ] && [ -r "${MIRROR_CA_FILE}" ]; then
    grep -q 'BEGIN CERTIFICATE' "${MIRROR_CA_FILE}" || die "MIRROR_CA_FILE=${MIRROR_CA_FILE} holds no PEM certificate"
    if [ "$(realpath "${MIRROR_CA_FILE}")" = "$(realpath -m "${CA_FILE}")" ]; then
      msg "Keeping ${CA_FILE} (the site MIRROR_CA_FILE) unchanged"
    else
      cp "${MIRROR_CA_FILE}" "${CA_FILE}"
      msg "Copied the site MIRROR_CA_FILE ${MIRROR_CA_FILE} -> ${CA_FILE}"
    fi
  else
    [ -z "${MIRROR_CA_FILE:-}" ] || warn "MIRROR_CA_FILE=${MIRROR_CA_FILE} is not readable; trying the hub's additionalTrustedCA"
    cm="$(${KUBECTL} get image.config.openshift.io cluster -o jsonpath='{.spec.additionalTrustedCA.name}' 2>/dev/null || true)"
    [ -n "${cm}" ] || die "no trusted mirror CA: set the site MIRROR_CA_FILE to the mirror registry CA bundle (or give image.config.openshift.io/cluster an additionalTrustedCA), or re-run with --no-ca"
    ${KUBECTL} get configmap "${cm}" -n openshift-config -o json \
      | jq -r --arg hosts "${MIRROR_HOSTS}" '
          ($hosts | split("\n") | map(select(. != "") | sub(":"; ".."))) as $keys
          | (.data // {}) | to_entries | map(select(.key as $k | any($keys[]; . == $k)))
          | sort_by(.key) | .[] | .value' > "${CA_FILE}.tmp" \
      || { rm -f "${CA_FILE}.tmp"; die "could not read openshift-config/${cm}"; }
    grep -q 'BEGIN CERTIFICATE' "${CA_FILE}.tmp" || { rm -f "${CA_FILE}.tmp"; die "openshift-config/${cm} has no CA for the mirror hosts ($(echo ${MIRROR_HOSTS})): set the site MIRROR_CA_FILE"; }
    mv "${CA_FILE}.tmp" "${CA_FILE}"
    msg "Wrote ${CA_FILE} from openshift-config/${cm} ($(grep -c 'BEGIN CERTIFICATE' "${CA_FILE}") cert(s))"
  fi
fi

echo ""
echo "Next steps:"
echo "  1. Load into Vault:   ./scripts/load-existing-vault.sh"
echo "                        (writes secret/hub/registryConfig and mirrorCA)"
echo "  2. Publish + deploy: ./scripts/publish-coco-charts.sh (coco-initdata) then"
echo "                        APPLY=true ./scripts/deploy-coco-hub.sh"
echo "  3. Re-run the coco-initdata Job (redeploy bumps it) so initdata + its"
echo "     init_data reference value are regenerated, then restart the CC pods."
echo ""
echo "TLS: mirrors are emitted secure (HTTPS). The guest trusts the mirror via the"
echo "     CA bundle above, injected into cdh.toml extra_root_certificates by the"
echo "     coco-initdata gzipper. Re-run with --insecure only if the mirror serves HTTP."
echo "AUTH: this script copies no credential. The guest authenticates with the dedicated TDX"
echo "     registry credential (site TDX_REGISTRY_AUTH_FILE -> Vault secret/hub/tdxRegistryAuth)."
